const WINNERS: Record<string, Winner | undefined> = winnersData;

function resolvePhoto(winner: Winner) {
  const fixed = FIXED_PHOTOS[winner.profileUrl];
  if (fixed) return fixed;
  return winner.photo && import.meta.env.BASE_URL + winner.photo;
}

// iMafia's Month Rating starts in March 2026.
const FIRST_YEAR = 2026;
const FIRST_MONTH_INDEX = 2;
const OLDEST_YEAR_TAB = 2023;

const MONTH_NAMES = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

export type WinnerMonth = {
  key: string;
  year: number;
  name: string;
  winner?: Winner;
};

function lastFinishedMonth(now: Date) {
  return new Date(now.getFullYear(), now.getMonth() - 1, 1);
}

export function buildMonths(now: Date): WinnerMonth[] {
  const last = lastFinishedMonth(now);
  const months: WinnerMonth[] = [];
  for (let year = FIRST_YEAR; year <= last.getFullYear(); year++) {
    const lastMonth = year === last.getFullYear() ? last.getMonth() : 11;
    const firstMonth = year === FIRST_YEAR ? FIRST_MONTH_INDEX : 0;
    for (let month = firstMonth; month <= lastMonth; month++) {
      const key = `${year}-${String(month + 1).padStart(2, "0")}`;
      const winner = WINNERS[key];
      months.push({
        key,
        year,
        name: MONTH_NAMES[month],
        winner: winner && { ...winner, photo: resolvePhoto(winner) },
      });
    }
  }
  return months;
}

export function buildYearTabs(now: Date) {
  const tabs: { year: number; hasData: boolean }[] = [];
  for (let year = lastFinishedMonth(now).getFullYear(); year >= OLDEST_YEAR_TAB; year--) {
    tabs.push({ year, hasData: year >= FIRST_YEAR });
  }
  return tabs;
}
